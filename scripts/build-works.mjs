import { promises as fs } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const root = process.cwd();
const worksDir = path.join(root, 'works');
const dataDir = path.join(root, 'assets', 'data');
const thumbsDir = path.join(worksDir, 'thumbs');
const fullDir = path.join(worksDir, 'full');

const imageExt = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif', '.tif', '.tiff']);

const slugify = (value) =>
  value
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

const fileSlug = (file) => slugify(path.basename(file, path.extname(file)));

const prettyName = (file) =>
  path
    .basename(file, path.extname(file))
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/[-_]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\w/g, (character) => character.toUpperCase());

const toUrl = (file) =>
  path
    .relative(root, file)
    .split(path.sep)
    .map(encodeURIComponent)
    .join('/');

async function walk(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;

    const fullPath = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      if (entry.name === 'thumbs' || entry.name === 'full') continue;
      files.push(...(await walk(fullPath)));
    } else {
      files.push(fullPath);
    }
  }

  return files;
}

async function main() {
  let meta = { artworks: {} };

  try {
    meta = JSON.parse(await fs.readFile(path.join(worksDir, 'meta.json'), 'utf8'));
    meta.artworks ??= {};
  } catch {
    console.warn('No works/meta.json found, using filenames only.');
  }

  await fs.mkdir(dataDir, { recursive: true });
  await fs.mkdir(thumbsDir, { recursive: true });
  await fs.mkdir(fullDir, { recursive: true });

  const files = await walk(worksDir);
  const images = files.filter((file) => imageExt.has(path.extname(file).toLowerCase()));

  const artworks = [];

  for (const file of images.sort((a, b) => a.localeCompare(b))) {
    const slug = fileSlug(file);
    const custom = meta.artworks[slug] ?? {};
    const title = custom.title ?? prettyName(file);
    const medium = custom.medium ?? 'Drawing';
    const thumbName = `${slug}-900.webp`;
    const fullName = `${slug}-1600.webp`;
    const thumbPath = path.join(thumbsDir, thumbName);
    const fullPath = path.join(fullDir, fullName);

    await sharp(file)
      .rotate()
      .resize({ width: 900, withoutEnlargement: true })
      .webp({ quality: 84, effort: 5 })
      .toFile(thumbPath);

    await sharp(file)
      .rotate()
      .resize({ width: 1600, withoutEnlargement: true })
      .webp({ quality: 87, effort: 5 })
      .toFile(fullPath);

    const thumb = await sharp(thumbPath).metadata();

    artworks.push({
      id: slug,
      title,
      medium,
      year: custom.year ?? null,
      src: toUrl(thumbPath),
      full: toUrl(fullPath),
      original: toUrl(file),
      width: thumb.width,
      height: thumb.height,
      order: custom.order ?? 999
    });

    console.log(`artwork  ${title}  ${thumb.width}x${thumb.height}`);
  }

  artworks.sort((a, b) => a.order - b.order || a.title.localeCompare(b.title));

  const manifest = {
    generated: new Date().toISOString(),
    artworks
  };

  await fs.writeFile(
    path.join(dataDir, 'works.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
    'utf8'
  );

  const worksHtmlPath = path.join(root, 'works.html');
  let worksHtml = await fs.readFile(worksHtmlPath, 'utf8');
  const firstArtwork = artworks[0];
  const preload = firstArtwork
    ? `<link rel="preload" as="image" href="${firstArtwork.src}" imagesrcset="${firstArtwork.src} 900w, ${firstArtwork.full} 1600w" imagesizes="(min-width: 1024px) 1200px, 300px" fetchpriority="high">`
    : '';

  const marker = /<!-- works-preload -->[\s\S]*?<!-- \/works-preload -->/;

  if (marker.test(worksHtml)) {
    worksHtml = worksHtml.replace(
      marker,
      `<!-- works-preload -->\n  ${preload}\n  <!-- /works-preload -->`
    );
    await fs.writeFile(worksHtmlPath, worksHtml, 'utf8');
  } else {
    console.warn('works.html is missing the works-preload marker');
  }

  const en = JSON.parse(await fs.readFile(path.join(root, 'assets/i18n/en.json'), 'utf8'));
  const de = JSON.parse(await fs.readFile(path.join(root, 'assets/i18n/de.json'), 'utf8'));

  const siteData = `/* Generated by npm run build:works. Do not edit by hand. */\nwindow.SHRAVAN_DATA = ${JSON.stringify({ i18n: { en, de }, works: manifest }, null, 2)};\n`;
  await fs.writeFile(path.join(root, 'assets/js/site-data.js'), siteData, 'utf8');

  console.log(
    `\nWrote ${artworks.length} artwork(s) to assets/data/works.json and assets/js/site-data.js`
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
